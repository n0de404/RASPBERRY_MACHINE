const fs = require('node:fs');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../server/server.py'), 'utf8');
const start = source.indexOf('  function pdrMachineStatusRows(');
const end = source.indexOf('  function renderFinishedShiftPdr(', start);
const build = new Function('pdrAmBoundaryHour','pdrNightBoundaryHour','MACHINE_NAME_MAP',source.slice(start,end)+';return pdrMachineStatusRows;')(7,19,{M1:'IMM 301'});
const now = Date.parse('2026-10-07T04:00:00Z');
const record = {machine_code:'M1',status:'No schedule',started_at_utc:'2026-10-06T10:00:00Z',ended_at_utc:'2026-10-06T23:30:00Z'};
const rows = build([record],{},now);
assert.equal(rows.length,3, 'status spans AM, PM, and following AM');
assert.deepEqual(rows.map(r=>r.started_at_utc),['2026-10-06T10:00:00.000Z','2026-10-06T11:00:00.000Z','2026-10-06T23:00:00.000Z']);
assert.ok(rows.every(r=>r.review_status==='No schedule' && r.manpower_count===0 && r.machine_name==='IMM 301'));
assert.equal(build([{...record,status:'Inactive'}],{},now).length,0);
assert.equal(build([{...record,status:'Working'}],{},now).length,0);
assert.equal(build([{...record,started_at_utc:'invalid'}],{},now).length,0);
const active = {...record,ended_at_utc:''};
assert.equal(build([active],{M1:active},now).length,3,'active archive and override are not duplicated');
assert.equal(build([],{M1:active},now).length,3,'override used if archive entry missing');
assert.equal(build([{...record,ended_at_utc:'2026-10-06T11:00:00Z'}],{},now).length,1,'status ending at boundary does not spill into PM');
console.log('PASS: status rows, shift boundaries, exclusions, and active override fallback');
