const fs = require('node:fs');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../server/server.py'), 'utf8');
assert.match(source,/class="machine-time-btn"/,'machine cards expose a Time button');
assert.match(source,/id="machineTimeOverlay"/,'machine runtime modal exists');
assert.match(source,/id="machineTimeRpi"/,'machine runtime modal shows Raspberry Pi uptime');
const noScheduleStart = source.indexOf('  function isNoScheduleStatus(');
const noScheduleEnd = source.indexOf('  function stopMachineNoScheduleAnimation(', noScheduleStart);
const start = source.indexOf('  const machineUptimeState = new Map();');
const end = source.indexOf('  function machineCardHtml(', start);
const storage = new Map();
const localStorage = {getItem:key=>storage.get(key),setItem:(key,value)=>storage.set(key,value)};
const load = () => new Function('localStorage',source.slice(noScheduleStart,noScheduleEnd)+source.slice(start,end)+';return {machineUptimeStarted,machineUptimeBreakdown};')(localStorage);
let helpers = load();
let uptime = helpers.machineUptimeStarted;
const now = Date.parse('2026-10-07T04:00:00Z');
const session = {job_started_at:'2026-10-07T02:00:00Z'};
assert.equal(uptime(session,'M1','active',null,now),'2026-10-07T02:00:00.000Z');
assert.equal(uptime({},'M1','disconnected',null,now+1000),'2026-10-07T02:00:00.000Z');
assert.equal(uptime({},'M1','maintenance',{started_at_utc:'2026-10-07T03:00:00Z'},now+2000),'2026-10-07T02:00:00.000Z');
helpers=load();
uptime=helpers.machineUptimeStarted;
assert.equal(uptime({},'M1','active',null,now+3000),'2026-10-07T02:00:00.000Z','refresh preserves start');
assert.equal(uptime(session,'M1','inactive',null,now+4000),'2026-10-07T02:00:00.000Z','inactive preserves machine runtime');
assert.equal(uptime(session,'M1','active',null,now+5000),'2026-10-07T02:00:00.000Z','reactivation keeps the original start');
assert.equal(uptime(session,'M1','maintenance',{status:'Scheduled for fix'},now+5500),'2026-10-07T02:00:00.000Z','scheduled fix keeps uptime continuous');
assert.equal(uptime(session,'M1','maintenance',{status:'Not working'},now+5750),'2026-10-07T02:00:00.000Z','not working keeps uptime continuous');
assert.equal(uptime({},'M2','maintenance',{started_at_utc:'2026-10-07T01:00:00Z'},now),'2026-10-07T01:00:00.000Z');
assert.equal(uptime({},'M3','active',null,now),'2026-10-07T04:00:00.000Z');
assert.equal(uptime(session,'M1','maintenance',{status:' no-schedule '},now+6000),'','no schedule hides uptime');
helpers=load();
uptime=helpers.machineUptimeStarted;
assert.equal(uptime(session,'M1','maintenance',{status:'No schedule'},now+7000),'','no schedule stays excluded after refresh');
assert.equal(uptime(session,'M1','active',null,now+8000),'2026-10-07T04:00:08.000Z','uptime restarts after no schedule');

const running = {production_session_id:'S1',job_code:'JOB-1',job_started_at:'2026-10-07T02:00:00Z',downtime_total_seconds:3600};
assert.equal(uptime(running,'M4','active',null,now),'2026-10-07T02:00:00.000Z');
assert.deepEqual(helpers.machineUptimeBreakdown('M4',now),{totalSeconds:7200,downtimeSeconds:3600,utilizedSeconds:3600});
uptime({...running,downtime_total_seconds:5400},'M4','maintenance',null,now+1800000);
assert.deepEqual(helpers.machineUptimeBreakdown('M4',now+1800000),{totalSeconds:9000,downtimeSeconds:5400,utilizedSeconds:3600},'PDR downtime reduces utilized time but not total uptime');
uptime({production_session_id:'S2',job_code:'JOB-2',downtime_total_seconds:600},'M4','active',null,now+1801000);
assert.deepEqual(helpers.machineUptimeBreakdown('M4',now+1801000),{totalSeconds:9001,downtimeSeconds:6000,utilizedSeconds:3001},'downtime accumulates when the job or shift session changes');
helpers=load();
assert.deepEqual(helpers.machineUptimeBreakdown('M4',now+1802000),null,'state is loaded when uptime is next evaluated');
helpers.machineUptimeStarted({production_session_id:'S2',job_code:'JOB-2',downtime_total_seconds:600},'M4','active',null,now+1802000);
assert.deepEqual(helpers.machineUptimeBreakdown('M4',now+1802000),{totalSeconds:9002,downtimeSeconds:6000,utilizedSeconds:3002},'refresh preserves accumulated downtime');

console.log('PASS: total uptime, utilized time, downtime, refresh persistence, and status changes');
